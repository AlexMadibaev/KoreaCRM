import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

const base = process.env.KOREACRM_TEST_API_URL;
const login = process.env.KOREACRM_TEST_LOGIN;
const password = process.env.KOREACRM_TEST_PASSWORD;
if (!base || !login || !password || process.env.KOREACRM_ISOLATED_TEST_DB !== '1') throw new Error('Run only against a separate test database with KOREACRM_ISOLATED_TEST_DB=1');
let token = '';
async function request(method, path, body, expected = 200) {
  const response = await fetch(`${base}${path}`, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const result = await response.json();
  assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(result)}`);
  return result;
}

const auth = await request('POST', '/auth/login', { login, password }, 201);
token = auth.accessToken;
const storeId = (await request('GET', '/stores'))[0].id;
const paymentMethods = await request('GET', '/sale-payment-methods');
const cardId = paymentMethods.find(method => method.code === 'CARD').id;
const cashId = paymentMethods.find(method => method.code === 'CASH').id;
const suffix = randomUUID().slice(0, 8);
const product = await request('POST', '/products', { name: `Loyalty test ${suffix}`, sku: `LOYALTY-${suffix}`, barcodes: [] }, 201);
await request('PATCH', `/stores/${storeId}/products/${product.id}/settings`, { priceMinor: 50000, minStock: 0, active: true });
const supplier = await request('POST', '/suppliers', { name: `Loyalty supplier ${suffix}` }, 201);
const purchase = await request('POST', `/stores/${storeId}/purchases`, { supplierId: supplier.id, number: `LOYALTY-${suffix}`, items: [{ productId: product.id, quantityOrdered: 5, purchasePriceMinor: '25000', salePriceMinor: '50000' }] }, 201);
await request('POST', `/stores/${storeId}/purchases/${purchase.id}/submit`, undefined, 201);
await request('POST', `/stores/${storeId}/purchases/${purchase.id}/receivings`, { operationId: randomUUID(), items: [{ purchaseItemId: purchase.items[0].id, quantity: 5, batchNumber: `B-${suffix}` }] }, 201);
const customer = await request('POST', '/customers', { firstName: 'Test', lastName: suffix, phone: `+992900${String(Math.floor(Math.random() * 1000000)).padStart(6, '0')}` }, 201);
const deviceId = `loyalty-test-${suffix}`;
await request('POST', `/stores/${storeId}/pos-devices`, { deviceId, appVersion: 'loyalty-test' }, 201);
const settings = await request('GET', '/loyalty/settings');
assert.equal(settings.mode, 'DISCOUNT');
assert.deepEqual(settings.tiers.map(tier => [tier.minimumMinor, tier.percent]), [['50000', '7'], ['80000', '10']]);
const sale = (discountMinor, operationId = randomUUID()) => ({ operationId, deviceId, customerId: customer.id, items: [{ productId: product.id, quantity: 1, discountMinor }], payments: [{ paymentMethodId: cardId, amountMinor: String(50000 - Number(discountMinor)) }] });
await request('POST', `/stores/${storeId}/sales`, sale('0'), 400);
const thresholdSale = await request('POST', `/stores/${storeId}/sales`, sale('3500'), 201);
assert.equal(thresholdSale.discountMinor, '3500');
await request('PATCH', `/customers/${customer.id}/discount`, { discountPercent: '12' });
const activity = await request('GET', `/customers/${customer.id}/activity`);
assert.ok(activity.items.some(item => item.kind === 'PROFILE' && item.detail.includes('0%') && item.detail.includes('12%')));
await request('POST', `/stores/${storeId}/sales`, sale('6000'), 201);
await request('PATCH', '/loyalty/settings', { ...settings, excludedProductIds: [product.id] });
await request('POST', `/stores/${storeId}/sales`, sale('0'), 201);
const bonusSettings = { ...settings, mode: 'BONUS', bonusEarnPercent: '10', consultantEarnPercent: '5', excludedProductIds: [] };
await request('PATCH', '/loyalty/settings', bonusSettings);
await request('POST', `/stores/${storeId}/sales`, sale('0'), 201);
const earnedCustomer = await request('GET', `/customers/${customer.id}`);
assert.equal(earnedCustomer.bonusBalanceMinor, '5000');
const employeeRewards = await request('GET', '/employees/me/rewards');
assert.equal(employeeRewards.balanceMinor, '2500');
assert.equal(employeeRewards.saleCount, 4);
const shift = await request('POST', `/stores/${storeId}/finance/cash-shifts`, { deviceId, openingCashMinor: '0' }, 201);
const cashSale = await request('POST', `/stores/${storeId}/sales`, { ...sale('0'), cashShiftId: shift.id, payments: [{ paymentMethodId: cashId, amountMinor: '50000' }] }, 201);
assert.equal((await request('GET', `/customers/${customer.id}`)).bonusBalanceMinor, '10000');
await request('POST', `/stores/${storeId}/sales/${cashSale.id}/return`, { operationId: randomUUID(), deviceId, cashShiftId: shift.id, reason: 'Loyalty test return' }, 201);
assert.equal((await request('GET', `/customers/${customer.id}`)).bonusBalanceMinor, '5000');
assert.equal((await request('GET', '/employees/me/rewards')).balanceMinor, '2500');
const localParts = Object.fromEntries(new Intl.DateTimeFormat('en-US', { timeZone: 'Asia/Dushanbe', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(new Date()).map(part => [part.type, part.value]));
const localDate = `${localParts.year}-${localParts.month}-${localParts.day}`;
const weekday = new Date(`${localDate}T00:00:00Z`).getUTCDay();
await request('PATCH', '/loyalty/settings', { ...settings, promotions: [{ id: randomUUID(), targetType: 'PRODUCT', targetId: product.id, percent: '20', daysOfWeek: [weekday], startDate: localDate, endDate: localDate, active: true }] });
const promotionalSale = await request('POST', `/stores/${storeId}/sales`, sale('10000'), 201);
assert.equal(promotionalSale.discountMinor, '10000');
console.log('Real database loyalty flow: OK');
